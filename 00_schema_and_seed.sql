PRAGMA foreign_keys = ON;
DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS sales_reps;
DROP TABLE IF EXISTS products;
DROP TABLE IF EXISTS customers;
CREATE TABLE customers(customer_id INTEGER PRIMARY KEY, customer_name TEXT NOT NULL, home_region TEXT NOT NULL);
CREATE TABLE products(product_id INTEGER PRIMARY KEY, product_name TEXT NOT NULL, category TEXT NOT NULL, unit_price REAL NOT NULL);
CREATE TABLE sales_reps(rep_id INTEGER PRIMARY KEY, rep_name TEXT NOT NULL, region TEXT NOT NULL, sales_target REAL NOT NULL);
CREATE TABLE orders(
 order_id INTEGER PRIMARY KEY, customer_id INTEGER NOT NULL, product_id INTEGER NOT NULL,
 rep_id INTEGER NOT NULL, order_date TEXT NOT NULL, units INTEGER NOT NULL, amount REAL,
 status TEXT NOT NULL CHECK(status IN ('Completed','Pending','Disputed')),
 region TEXT NOT NULL, order_code TEXT NOT NULL UNIQUE,
 FOREIGN KEY(customer_id) REFERENCES customers(customer_id),
 FOREIGN KEY(product_id) REFERENCES products(product_id),
 FOREIGN KEY(rep_id) REFERENCES sales_reps(rep_id)
);

